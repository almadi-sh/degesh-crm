def render_contract_document_text(contract: Contract) -> str:
    document = normalize_contract_document_payload(contract.contract_document) if contract.contract_document else build_default_contract_document(contract)
    header = document.get("header", {})
    signatures = document.get("signatures", {})
    sections = []

    title = header.get("title", "Договор")
    contract_number = header.get("contract_number", contract.contract_number)
    city = header.get("city", "г. Астана")
    date = header.get("date", "")
    sections.append(f"{title} {contract_number}")
    sections.append(f"{city}\t\t{date}")
    sections.append("")

    buyer_name = contract.customer.name if contract.customer else "ТОО «Покупатель»"
    buyer_bin = contract.customer.bin_iin if contract.customer else ""
    buyer_address = contract.customer.address if contract.customer else ""
    sections.append("Информация о покупателе:")
    sections.append(f"Наименование: {buyer_name}")
    if buyer_bin:
        sections.append(f"БИН/ИИН: {buyer_bin}")
    if buyer_address:
        sections.append(f"Адрес: {buyer_address}")
    sections.append("")

    sections.append(document.get("intro", ""))
    sections.append("")

    sections.append("Спецификация (Contract items):")
    if contract.items:
        for index, item in enumerate(contract.items, start=1):
            product_name = item.product.name if item.product else f"Product #{item.product_id}"
            sections.append(
                f"{index}. {product_name} — {item.quantity} x {item.price:.2f} "
                f"= {item.total_amount:.2f}"
            )
            if item.delivery_enabled and item.delivery_terms:
                sections.append(f"   Условия доставки: {item.delivery_terms}")
    else:
        sections.append("Нет позиций.")
    sections.append("")

    for clause in document.get("clauses", []):
        title = clause.get("title", "")
        if title:
            sections.append(title)

        blocks = _get_clause_blocks(clause)

        if blocks:
            clause_id = str(clause.get("id", "")).strip()
            numbered_index = 1
            for block in blocks:
                block_type = (block or {}).get("type")
                if block_type == "paragraph":
                    text = (block.get("text") or "").strip()
                    if text:
                        sections.append(text)
                elif block_type == "numbered":
                    for item in block.get("items") or []:
                        text = str(item).strip()
                        if not text:
                            continue
                        prefix = f"{clause_id}.{numbered_index}. " if clause_id else f"{numbered_index}. "
                        sections.append(f"{prefix}{text}")
                        numbered_index += 1
                elif block_type == "bullets":
                    for item in block.get("items") or []:
                        text = str(item).strip()
                        if text:
                            sections.append(f"- {text}")
        else:
            for item in clause.get("body") or []:
                text = str(item).strip()
                if text:
                    sections.append(text)

        sections.append("")

    sections.append("Подписи сторон:")
    sections.append(f"{signatures.get('seller_label', '«Продавец»')}")
    sections.append(f"{signatures.get('seller_position', '')}")
    sections.append(f"{signatures.get('seller_name', '')}")
    sections.append(f"{signatures.get('seller_stamp', '')}")
    sections.append("")
    sections.append(f"{signatures.get('buyer_label', '«Покупатель»')}")
    sections.append(f"{signatures.get('buyer_position', '')}")
    sections.append(f"{signatures.get('buyer_name', '')}")
    sections.append(f"{signatures.get('buyer_stamp', '')}")

    return "\n".join([line for line in sections if line is not None])


def _set_page_margins(doc: Document) -> None:
    section = doc.sections[0]
    section.left_margin = Cm(1.91)
    section.right_margin = Cm(1.91)
    section.top_margin = Cm(2.54)
    section.bottom_margin = Cm(2.54)


def _add_page_number(run):
    run.add_text("Страница ")
    fld_char_begin = OxmlElement("w:fldChar")
    fld_char_begin.set(qn("w:fldCharType"), "begin")
    instr_text = OxmlElement("w:instrText")
    instr_text.set(qn("xml:space"), "preserve")
    instr_text.text = " PAGE "
    fld_char_end = OxmlElement("w:fldChar")
    fld_char_end.set(qn("w:fldCharType"), "end")

    run._r.append(fld_char_begin)
    run._r.append(instr_text)
    run._r.append(fld_char_end)


def _add_footer(doc: Document) -> None:
    section = doc.sections[0]
    footer = section.footer

    footer_paragraph = footer.paragraphs[0]
    footer_paragraph.text = ""
    footer_paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT
    footer_paragraph.add_run("ТОО «Дегеш Агро ЛТД»")

    page_paragraph = footer.add_paragraph()
    page_paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    _add_page_number(page_paragraph.add_run())


def _add_justified_paragraph(doc: Document, text: str, spacing_after: Pt | None = None):
    paragraph = doc.add_paragraph(text)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    paragraph.paragraph_format.space_before = Pt(0)
    paragraph.paragraph_format.space_after = spacing_after if spacing_after is not None else Pt(0)
    return paragraph


def _add_clause_blocks(doc: Document, clause: dict) -> None:
    blocks = _get_clause_blocks(clause)
    if blocks:
        clause_id = str(clause.get("id", "")).strip()
        numbered_index = 1
        for block in blocks:
            block_type = (block or {}).get("type")
            if block_type == "paragraph":
                text = (block.get("text") or "").strip()
                if text:
                    _add_justified_paragraph(doc, text)
            elif block_type == "numbered":
                for item in block.get("items") or []:
                    text = str(item).strip()
                    if not text:
                        continue
                    prefix = f"{clause_id}.{numbered_index}. " if clause_id else f"{numbered_index}. "
                    _add_justified_paragraph(doc, f"{prefix}{text}")
                    numbered_index += 1
            elif block_type == "bullets":
                for item in block.get("items") or []:
                    text = str(item).strip()
                    if text:
                        _add_justified_paragraph(doc, f"- {text}")
        return

    for item in clause.get("body") or []:
        text = str(item).strip()
        if text:
            _add_justified_paragraph(doc, text)


def render_contract_document_docx(contract: Contract) -> bytes:
    document_payload = normalize_contract_document_payload(contract.contract_document) if contract.contract_document else build_default_contract_document(contract)
    header = document_payload.get("header", {})
    signatures = document_payload.get("signatures", {})

    doc = Document()
    _set_page_margins(doc)
    _add_footer(doc)

    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)
    style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    style.paragraph_format.space_before = Pt(0)
    style.paragraph_format.space_after = Pt(0)

    title = header.get("title", "Договор")
    contract_number = header.get("contract_number", contract.contract_number)
    city = header.get("city", "г. Астана")
    contract_date = header.get("date", "")

    number_part = str(contract_number).strip()
    if not number_part.startswith("№"):
        number_part = f"№{number_part}"
    heading = doc.add_paragraph(f"{title} {number_part}")
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
    heading.paragraph_format.space_before = Pt(0)
    heading.paragraph_format.space_after = Pt(0)
    if heading.runs:
        heading.runs[0].bold = True

    section = doc.sections[0]
    city_line = doc.add_paragraph()
    city_line.alignment = WD_ALIGN_PARAGRAPH.LEFT
    city_line.paragraph_format.space_before = Pt(0)
    city_line.paragraph_format.space_after = Pt(0)
    city_line.paragraph_format.tab_stops.add_tab_stop(
        section.page_width - section.left_margin - section.right_margin,
        WD_TAB_ALIGNMENT.RIGHT,
    )
    city_run = city_line.add_run(city)
    city_run.bold = True
    city_line.add_run("\t")
    date_run = city_line.add_run(f"Дата {contract_date}")
    date_run.bold = True

    _add_justified_paragraph(doc, document_payload.get("intro", ""), spacing_after=Pt(8))

    for clause in document_payload.get("clauses", []):
        clause_title = (clause.get("title") or "").strip()
        if clause_title:
            title_paragraph = doc.add_paragraph(clause_title)
            title_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
            title_paragraph.paragraph_format.space_before = Pt(0)
            title_paragraph.paragraph_format.space_after = Pt(0)
            for run in title_paragraph.runs:
                run.bold = True

        _add_clause_blocks(doc, clause)

    doc.add_paragraph("")
    signatures_line = doc.add_paragraph("Подписи сторон:")
    signatures_line.runs[0].bold = True

    signatures_table = doc.add_table(rows=3, cols=2)
    signatures_table.style = "Table Grid"
    signatures_table.cell(0, 0).text = signatures.get("seller_label", "«Продавец»")
    signatures_table.cell(0, 1).text = signatures.get("buyer_label", "«Покупатель»")

    signatures_table.cell(1, 0).text = signatures.get("seller_position", "Директор")
    signatures_table.cell(1, 1).text = signatures.get("buyer_position", "Директор")

    signatures_table.cell(2, 0).text = (
        f"{signatures.get('seller_name', '')}\n{signatures.get('seller_stamp', '')}"
    )
    signatures_table.cell(2, 1).text = (
        f"{signatures.get('buyer_name', '')}\n{signatures.get('buyer_stamp', '')}"
    )

    buffer = BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer.read()


def _register_pdf_font() -> str:
    font_name = "Helvetica"
    for font_path in (
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/local/share/fonts/DejaVuSans.ttf",
    ):
        if Path(font_path).exists():
            pdfmetrics.registerFont(TTFont("DejaVuSans", font_path))
            font_name = "DejaVuSans"
            break
    return font_name


def render_contract_document_pdf(contract: Contract, document_payload_override: dict | None = None) -> bytes:
    document_payload = (
        normalize_contract_document_payload(document_payload_override)
        if document_payload_override
        else normalize_contract_document_payload(contract.contract_document)
        if contract.contract_document
        else build_default_contract_document(contract)
    )
    header = document_payload.get("header", {})
    signatures = document_payload.get("signatures", {})
    font_name = _register_pdf_font()

    styles = getSampleStyleSheet()
    normal_style = ParagraphStyle(
        "ContractNormal",
        parent=styles["Normal"],
        fontName=font_name,
        fontSize=11,
        leading=15,
    )
    heading_style = ParagraphStyle(
        "ContractHeading",
        parent=normal_style,
        alignment=1,
        fontSize=13,
        leading=17,
        spaceAfter=8,
    )
    clause_title_style = ParagraphStyle(
        "ContractClauseTitle",
        parent=normal_style,
        alignment=1,
        spaceBefore=6,
        spaceAfter=4,
    )

    number_part = str(header.get("contract_number", contract.contract_number)).strip()
    if not number_part.startswith("№"):
        number_part = f"№{number_part}"

    story: list = [
        Paragraph(
            f"<b>{escape(header.get('title', 'Договор'))} {escape(number_part)}</b>",
            heading_style,
        ),
        Paragraph(
            f"<b>{escape(header.get('city', 'г. Астана'))}</b> — <b>Дата {escape(header.get('date', ''))}</b>",
            normal_style,
        ),
        Spacer(1, 0.3 * cm),
        Paragraph(escape(document_payload.get("intro", "")), normal_style),
        Spacer(1, 0.2 * cm),
    ]

    for clause in document_payload.get("clauses", []):
        clause_title = (clause.get("title") or "").strip()
        if clause_title:
            story.append(Paragraph(f"<b>{escape(clause_title)}</b>", clause_title_style))

        blocks = _get_clause_blocks(clause)
        if blocks:
            clause_id = str(clause.get("id", "")).strip()
            numbered_index = 1
            for block in blocks:
                block_type = (block or {}).get("type")
                if block_type == "paragraph":
                    text = (block.get("text") or "").strip()
                    if text:
                        story.append(Paragraph(escape(text), normal_style))
                elif block_type == "numbered":
                    for item in block.get("items") or []:
                        text = str(item).strip()
                        if not text:
                            continue
                        prefix = f"{clause_id}.{numbered_index}. " if clause_id else f"{numbered_index}. "
                        story.append(Paragraph(f"{escape(prefix)}{escape(text)}", normal_style))
                        numbered_index += 1
                elif block_type == "bullets":
                    for item in block.get("items") or []:
                        text = str(item).strip()
                        if text:
                            story.append(Paragraph(f"• {escape(text)}", normal_style))
            continue

        for item in clause.get("body") or []:
            text = str(item).strip()
            if text:
                story.append(Paragraph(escape(text), normal_style))

    story.extend(
        [
            Spacer(1, 0.4 * cm),
            Paragraph("<b>Подписи сторон:</b>", normal_style),
            Spacer(1, 0.2 * cm),
        ]
    )

    signatures_table = Table(
        [
            [signatures.get("seller_label", "«Продавец»"), signatures.get("buyer_label", "«Покупатель»")],
            [signatures.get("seller_position", "Директор"), signatures.get("buyer_position", "Директор")],
            [
                f"{signatures.get('seller_name', '')}\n{signatures.get('seller_stamp', '')}",
                f"{signatures.get('buyer_name', '')}\n{signatures.get('buyer_stamp', '')}",
            ],
        ],
        colWidths=[8 * cm, 8 * cm],
    )
    signatures_table.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
                ("FONTNAME", (0, 0), (-1, -1), font_name),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(signatures_table)

    buffer = BytesIO()
    pdf = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=2 * cm,
        rightMargin=2 * cm,
        topMargin=2 * cm,
        bottomMargin=2 * cm,
    )
    pdf.build(story)
    buffer.seek(0)
    return buffer.read()
