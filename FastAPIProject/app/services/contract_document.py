def _extract_clause_body_items(clause_id: str, body: str) -> list[str]:
    items: list[str] = []
    clause_numbered_pattern = re.compile(rf"^{re.escape(clause_id)}\.\d+(?:\.\d+)*\.\s*(.+)$") if clause_id else None
    generic_numbered_pattern = re.compile(r"^\d+(?:\.\d+)*[.)]\s*(.+)$")

    for raw_line in body.split("\n"):
        line = raw_line.strip()
        if not line:
            continue

        if line.startswith("-"):
            cleaned = line.lstrip("-").strip()
            if cleaned:
                items.append(cleaned)
            continue

        numbered_text = ""
        if clause_numbered_pattern:
            clause_match = clause_numbered_pattern.match(line)
            if clause_match:
                numbered_text = clause_match.group(1).strip()

        if not numbered_text:
            generic_match = generic_numbered_pattern.match(line)
            if generic_match:
                numbered_text = generic_match.group(1).strip()

        items.append(numbered_text or line)

    return items


def _parse_clause_body_blocks(clause_id: str, body: str) -> list[dict]:
    blocks: list[dict] = []
    dotted_numbered_pattern = re.compile(r"^(\d+(?:\.\d+)*\.)\s*(.+)$")
    paren_numbered_pattern = re.compile(r"^(\d+)\)\s*(.+)$")
    generic_numbered_pattern = re.compile(r"^(\d+)\.\s*(.+)$")

    def ensure_items_block(block_type: str):
        if not blocks or blocks[-1].get("type") != block_type:
            blocks.append({"type": block_type, "items": []})
        return blocks[-1]["items"]

    for raw_line in body.split("\n"):
        line = raw_line.strip()
        if not line:
            continue

        if line.startswith("-"):
            cleaned = line.lstrip("-").strip()
            if cleaned:
                ensure_items_block("bullets").append(cleaned)
            continue

        paren_match = paren_numbered_pattern.match(line)
        if paren_match:
            ensure_items_block("paren_numbered").append(paren_match.group(2).strip())
            continue

        dotted_match = dotted_numbered_pattern.match(line)
        if dotted_match:
            marker = dotted_match.group(1).strip()
            text = dotted_match.group(2).strip()
            ensure_items_block("explicit_numbered").append({"marker": marker, "text": text})
            continue

        generic_match = generic_numbered_pattern.match(line)
        if generic_match:
            marker = f"{generic_match.group(1).strip()}."
            text = generic_match.group(2).strip()
            ensure_items_block("explicit_numbered").append({"marker": marker, "text": text})
            continue

        blocks.append({"type": "paragraph", "text": line})

    return blocks


def _get_clause_blocks(clause: dict) -> list[dict]:
    clause_id = str(clause.get("id", "")).strip()
    clause_body = clause.get("body")
    blocks = clause.get("blocks") or []

    # `body` is what the current UI edits. If `blocks` are sent together with stale
    # values, we should rebuild them from `body` so exported/previewed content
    # reflects the latest user changes.
    if isinstance(clause_body, list):
        items = [str(item).strip() for item in clause_body if str(item).strip()]
        clause["body"] = items
        clause["blocks"] = [{"type": "numbered", "items": items}] if items else []
        return clause["blocks"]

    if isinstance(clause_body, str):
        normalized_items = _extract_clause_body_items(clause_id, clause_body)
        clause["body"] = normalized_items
        clause["blocks"] = _parse_clause_body_blocks(clause_id, clause_body)
        return clause["blocks"]

    if blocks:
        return blocks

    clause["body"] = []
    clause["blocks"] = []
    return []



def normalize_contract_document_payload(document: dict | None) -> dict:
    payload = document or {}
    clauses = payload.get("clauses") or []
    if not isinstance(clauses, list):
        payload["clauses"] = []
        return payload

    for clause in clauses:
        if isinstance(clause, dict):
            _get_clause_blocks(clause)

    return payload


def has_complete_contract_document(document: dict | None) -> bool:
    if not isinstance(document, dict):
        return False

    required_root_fields = {"header", "intro", "clauses", "signatures"}
    if not required_root_fields.issubset(document.keys()):
        return False

    header = document.get("header")
    if not isinstance(header, dict):
        return False

    required_header_fields = {"title", "contract_number", "city", "date"}
    if not required_header_fields.issubset(header.keys()):
        return False

    signatures = document.get("signatures")
    if not isinstance(signatures, dict):
        return False

    required_signature_fields = {
        "seller_label",
        "buyer_label",
        "seller_position",
        "buyer_position",
        "seller_name",
        "buyer_name",
        "seller_stamp",
        "buyer_stamp",
    }
    return required_signature_fields.issubset(signatures.keys())


def ensure_contract_document(contract: Contract) -> dict:
    if has_complete_contract_document(contract.contract_document):
        return normalize_contract_document_payload(contract.contract_document)
    return build_default_contract_document(contract)

